'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../../Web/app.js'), 'utf8');
const start = source.indexOf('function applyLiveVideoState(');
const end = source.indexOf('// 离开实时页或失焦', start);
assert(start >= 0 && end > start);
const toasts = [];
const live = { mediaState: '' };
const context = vm.createContext({ live, t: value => value, toast: value => toasts.push(value) });
vm.runInContext(source.slice(start, end), context);
context.applyLiveVideoState({ state: 'stalled', active: false });
context.applyLiveVideoState({ state: 'stalled', active: false });
assert.equal(live.mediaState, 'stalled');
assert.equal(toasts.length, 1, 'Repeated native events must not spam the user');
context.applyLiveVideoState({ state: 'stalled', active: true });
assert.equal(live.mediaState, '');
assert.equal(toasts.length, 2);
context.applyLiveVideoState({ state: 'unknown', active: false });
assert.equal(live.mediaState, 'stalled');
assert.match(source, /\$\('liveRetry'\)\.addEventListener\('click', \(\) => \{\s*live\.error = '';\s*liveRestart\(\);/);
console.log('PASS video state: non-blocking transition notices and full rebuild retry');
