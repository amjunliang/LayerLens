'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('Web/app.js', 'utf8');
const section = source.slice(source.indexOf('function drawableNodes('), source.indexOf('function syncModeUI()'));
const state = { mode: '3d', subtreeOnly: false, showLayers: false, nodes: new Map() };
const ctx = { state }; vm.createContext(ctx); vm.runInContext(section, ctx);
const node = (name, rect, children = [], extra = {}) => ({ name, rect, children, effHidden: false, ...extra });
const text = node('deep-content', [70, 10, 25, 25]);
const content = node('content', [0, 0, 100, 100], [node('wrapper', [0, 0, 100, 100], [text])]);
const menuLabel = node('menu-label', [75, 15, 10, 10]);
const menu = node('menu', [70, 10, 25, 25], [menuLabel]);
const root = node('window', [0, 0, 100, 100], [content, menu]);
const nodes = ctx.drawableNodes(root);
assert(menu.level > text.level, 'A later shallow menu must appear above earlier deep content');
assert(menuLabel.level > menu.level, 'Menu content must remain above its parent');
assert.equal(nodes.at(-1), menuLabel, 'Traversal and hit testing preserve UIKit sibling order');
const disjointA = node('a', [0, 0, 10, 10]);
const disjointB = node('b', [20, 0, 10, 10]);
ctx.drawableNodes(node('root', [0, 0, 100, 100], [disjointA, disjointB]));
assert(disjointA.level < disjointB.level, '3D depth follows the original paint order');
assert(disjointB.level <= 1, 'The overall depth stays within the original hierarchy depth');
state.mode = '2d'; ctx.drawableNodes(root);
assert(menu.level < text.level, '2D retains the original hierarchy depths');
console.log('PASS 3D stacking: later overlapping subtrees render above earlier content');
